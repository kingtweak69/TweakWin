static const struct map *find(NTSTATUS st)
{
    for (size_t i = 0; i < sizeof k_map / sizeof k_map[0]; i++)
        if (k_map[i].st == st) return &k_map[i];
    return NULL;
}

uint32_t tw_nt_to_win32(NTSTATUS st)
{
    const struct map *m = find(st);
    if (m) return m->win;
    /* Success / informational statuses that are not in the table map to
     * ERROR_SUCCESS; anything else is "no mapping" (317). */
    if ((uint32_t)st < 0x40000000u) return 0;
    return 317;
}

const char *tw_nt_status_name(NTSTATUS st)
{
    const struct map *m = find(st);
    return m ? m->name : NULL;
}
