NTSTATUS tw_nt_from_kb(int64_t e, int ctx)
{
    if (e >= 0) return STATUS_SUCCESS;
    switch (e) {
    case TW_KB_ENOSYS: return STATUS_NOT_IMPLEMENTED;
    case TW_KB_EFAULT:
        /* A range the kernel will not touch. For VM calls on a range that
         * is not (entirely) one reservation, NT reports the address. */
        return ctx == TW_KBC_VM ? STATUS_MEMORY_NOT_ALLOCATED : STATUS_ACCESS_VIOLATION;
    case TW_KB_EINVAL: return STATUS_INVALID_PARAMETER;
    case TW_KB_ENOMEM:
        return ctx == TW_KBC_HANDLE || ctx == TW_KBC_CREATE ? STATUS_INSUFFICIENT_RESOURCES : STATUS_NO_MEMORY;
    case TW_KB_EBADH:  return STATUS_INVALID_HANDLE;
    case TW_KB_EPERM:  return STATUS_ACCESS_DENIED;
    case TW_KB_EAGAIN: return STATUS_INSUFFICIENT_RESOURCES;
    case TW_KB_ESTATE: return ctx == TW_KBC_VM ? STATUS_CONFLICTING_ADDRESSES : STATUS_INVALID_PARAMETER;
    case TW_KB_ENOENT: return STATUS_OBJECT_NAME_NOT_FOUND;
    case TW_KB_EEXIST: return STATUS_OBJECT_NAME_COLLISION;
    case TW_KB_EACCES: return STATUS_ACCESS_DENIED;
    case TW_KB_EISDIR: return STATUS_FILE_IS_A_DIRECTORY;
    case TW_KB_ENOTDIR: return STATUS_OBJECT_PATH_NOT_FOUND;
    case TW_KB_ELOOP:  return STATUS_OBJECT_PATH_NOT_FOUND;
    case TW_KB_ENOTEMPTY: return STATUS_DIRECTORY_NOT_EMPTY;
    case TW_KB_EIO:    return STATUS_UNSUCCESSFUL;
    default:           return STATUS_UNSUCCESSFUL;
    }
}

